    function actualizarEstadisticas() {
        var total = Math.max(
            estado.totalContactos,
            estado.contactos.length
        );

        var perfiles = _getPerfiles();

        var online = estado.contactos.filter(function (c) {
            var p = perfiles.get(c.contacto_id);

            return p && p.online === true;
        }).length;

        var tEl = document.getElementById('totalContactos');

        if (tEl) {
            tEl.textContent = String(total || 0);
        }

        var oEl = document.getElementById('onlineContactos');

        if (oEl) {
            oEl.textContent = String(online || 0);
        }

        return {
            total: total,
            online: online
        };
    }

