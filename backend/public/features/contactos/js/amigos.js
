    /* ============================================================
       EVENTOS DE LA LISTA
       ============================================================ */

    /*
     * Delegación de eventos:
     * - El botón Mensaje abre directamente el chat.
     * - El botón Llamar abre el chat con acción de llamada.
     * - Los botones restantes conservan sus acciones.
     * - No se espera ninguna operación de red para navegar.
     */

    function instalarEventosLista() {
        var lista = document.getElementById(
            'contactosList'
        );

        if (!lista || lista.dataset.amigosEventos === '1') {
            return;
        }

        lista.dataset.amigosEventos = '1';

        lista.addEventListener('click', function (e) {
            var boton = e.target.closest(
                '[data-accion]'
            );

            if (boton) {
                var tarjeta = boton.closest(
                    '[data-contacto-id]'
                );

                if (!tarjeta) return;

                e.preventDefault();
                e.stopPropagation();

                var contactoId =
                    tarjeta.getAttribute('data-contacto-id');

                var filaId =
                    tarjeta.getAttribute('data-fila-id');

                var accion =
                    boton.getAttribute('data-accion');

                if (accion === 'mensaje') {
                    abrirMensaje(contactoId);
                    return;
                }

                if (accion === 'llamar') {
                    llamar(contactoId);
                    return;
                }

                if (accion === 'favorito') {
                    var item = estado.contactos.find(function (c) {
                        return String(c.id) === String(filaId);
                    });

                    if (item) {
                        toggleFavorito(
                            filaId,
                            !item.es_favorito
                        );
                    }

                    return;
                }

                if (accion === 'bloquear') {
                    bloquear(contactoId);
                    return;
                }

                if (accion === 'eliminar') {
                    eliminar(contactoId);
                    return;
                }

                return;
            }

            var avatar = e.target.closest(
                '.contacto-avatar'
            );

            if (avatar) {
                var tarjetaAvatar = avatar.closest(
                    '[data-contacto-id]'
                );

                if (tarjetaAvatar) {
                    e.preventDefault();
                    e.stopPropagation();

                    abrirPerfil(
                        tarjetaAvatar.getAttribute(
                            'data-contacto-id'
                        )
                    );
                }

                return;
            }

            var tarjeta = e.target.closest(
                '.contacto-card[data-contacto-id]'
            );

            if (tarjeta) {
                abrirMensaje(
                    tarjeta.getAttribute(
                        'data-contacto-id'
                    )
                );
            }
        });

        lista.addEventListener('keydown', function (e) {
            if (
                e.key !== 'Enter' &&
                e.key !== ' '
            ) {
                return;
            }

            var tarjeta = e.target.closest(
                '.contacto-card[data-contacto-id]'
            );

            if (!tarjeta) return;

            if (
                e.target.closest('button') ||
                e.target.closest('.contacto-avatar')
            ) {
                return;
            }

            e.preventDefault();

            abrirMensaje(
                tarjeta.getAttribute(
                    'data-contacto-id'
                )
            );
        });
    }

