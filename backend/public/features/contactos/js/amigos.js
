    function aplicarFiltro(nombre) {
        var valor = String(
            nombre || 'todos'
        ).toLowerCase();

        if (
            ['todos', 'online', 'favoritos', 'recientes']
                .indexOf(valor) === -1
        ) {
            valor = 'todos';
        }

        estado.filtroActual = valor;

        document.querySelectorAll(
            '.filtros .filtro'
        ).forEach(function (boton) {
            var activo =
                (boton.dataset.filtro || 'todos') === valor;

            boton.classList.toggle('active', activo);

            boton.setAttribute(
                'aria-pressed',
                activo ? 'true' : 'false'
            );
        });

        render(estado.contactos, null);

        return valor;
    }

    function setBusqueda(texto) {
        estado.textoBusqueda = String(
            texto || ''
        ).trim().toLowerCase();

        render(estado.contactos, null);

        return estado.textoBusqueda;
    }

    /* ============================================================
       SCROLL INFINITO
       ============================================================ */

    function _configurarScrollInfinito() {
        if (estado.observerScroll) {
            estado.observerScroll.disconnect();
            estado.observerScroll = null;
        }

        var sentinel = document.getElementById(
            'cargandoMasSentinel'
        );

        if (
            !sentinel ||
            !('IntersectionObserver' in window)
        ) {
            return;
        }

        estado.observerScroll =
            new IntersectionObserver(function (entries) {
                if (
                    entries[0] &&
                    entries[0].isIntersecting &&
                    estado.hayMas &&
                    !estado.textoBusqueda
                ) {
                    refrescar({
                        reset: false
                    });
                }

            }, {
                rootMargin: '300px',
                threshold: 0
            });

        estado.observerScroll.observe(sentinel);
    }

    function destruirScrollInfinito() {
        if (estado.observerScroll) {
            estado.observerScroll.disconnect();
            estado.observerScroll = null;
        }
    }

