    async function toggleFavorito(filaId, nuevoValor) {
        var client = _sb();
        var session = await _session();

        if (!client || !session) {
            return {
                ok: false
            };
        }

        var item = estado.contactos.find(function (c) {
            return String(c.id) === String(filaId);
        });

        if (!item) {
            return {
                ok: false
            };
        }

        var anterior = item.es_favorito;

        var clave = _clave(
            'favorito',
            filaId
        );

        if (_bloqueado(clave)) {
            return {
                ok: false
            };
        }

        _marcar(clave);

        item.es_favorito = nuevoValor === true;

        render(estado.contactos, null);

        try {
            if (
                window.SocialAcciones &&
                typeof window.SocialAcciones.toggleFavorito === 'function'
            ) {
                var resSocial =
                    await window.SocialAcciones.toggleFavorito(
                        filaId,
                        item.es_favorito
                    );

                if (!resSocial || !resSocial.ok) {
                    throw new Error(
                        'No se pudo guardar favorito'
                    );
                }

            } else {
                var r = await _withRetry(function () {
                    return client.from(CONFIG.TABLA)
                        .update({
                            es_favorito: item.es_favorito
                        })
                        .eq('id', filaId)
                        .eq('usuario_id', session.user.id);

                }, 'favorito');

                if (r.error) {
                    throw r.error;
                }

                _toast(
                    item.es_favorito
                        ? 'Favorito guardado.'
                        : 'Favorito quitado.',
                    'success'
                );
            }

            return {
                ok: true
            };

        } catch (err) {
            console.error(
                '[Amigos] Favorito:',
                _err(err)
            );

            item.es_favorito = anterior;

            render(estado.contactos, null);

            _toast(
                'Error al guardar favorito: ' + _err(err),
                'error'
            );

            return {
                ok: false
            };

        } finally {
            _liberar(clave);
        }
    }

    async function eliminar(contactoId) {
        var client = _sb();
        var session = await _session();

        if (!client || !session) {
            _toast('Inicia sesión.', 'error');

            return {
                ok: false
            };
        }

        if (!contactoId) {
            return {
                ok: false
            };
        }

        var confirmado = await _confirm({
            title: 'Eliminar contacto',
            message: '¿Eliminar a este contacto de tu red?',
            icon: '🗑️',
            confirmText: 'Eliminar',
            cancelText: 'Cancelar',
            danger: true
        });

        if (!confirmado) {
            return {
                ok: false
            };
        }

        var clave = _clave(
            'eliminar',
            contactoId
        );

        if (_bloqueado(clave)) {
            return {
                ok: false
            };
        }

        _marcar(clave);

        try {
            if (
                window.SocialAcciones &&
                typeof window.SocialAcciones.eliminarAmistad === 'function'
            ) {
                var resSocial =
                    await window.SocialAcciones.eliminarAmistad(
                        contactoId
                    );

                if (!resSocial || !resSocial.ok) {
                    throw new Error(
                        'No se pudo eliminar el contacto'
                    );
                }

            } else {
                var r = await _withRetry(function () {
                    return client.rpc(
                        CONFIG.RPC_ELIMINAR,
                        {
                            p_contacto_id: contactoId
                        }
                    );

                }, 'eliminar amistad');

                if (r.error) {
                    throw r.error;
                }

                _toast(
                    'Contacto eliminado.',
                    'success'
                );
            }

            await _refrescar({
                reset: true
            });

            return {
                ok: true
            };

        } catch (err) {
            console.error(
                '[Amigos] Eliminar:',
                _err(err)
            );

            _toast(
                'Error al eliminar: ' + _err(err),
                'error'
            );

            return {
                ok: false
            };

        } finally {
            _liberar(clave);
        }
    }

