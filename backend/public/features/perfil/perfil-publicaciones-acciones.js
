    async function senalPublicacion(d, sesion, tipo) {
        try {
            var actual = await sesion.client.from('publicacion_senales').select('tipo').eq('usuario_id', sesion.user.id).eq('publicacion_id', d.id).maybeSingle();
            if (actual.data && actual.data.tipo === tipo) {
                await sesion.client.from('publicacion_senales').delete().eq('usuario_id', sesion.user.id).eq('publicacion_id', d.id);
                toast('Preferencia quitada', 'success');
            } else {
                var r = await sesion.client.from('publicacion_senales').upsert({ usuario_id: sesion.user.id, publicacion_id: d.id, tipo: tipo });
                if (r.error) throw r.error;
                toast(tipo === 'interesa' ? 'Verás más contenido como este' : 'Verás menos contenido como este', 'success');
                if (tipo === 'no_interesa') ocultarTarjeta(d.id);
            }
        } catch (e) { console.error(e); toast('No se pudo guardar tu preferencia', 'error'); }
    }

    function ocultarTarjeta(id) {
        var card = document.querySelector('.publicacion-card[data-id="' + id + '"]');
        if (card) card.style.display = 'none';
    }

    async function alternarSuscripcion(d, sesion, suscrito) {
        try {
            if (suscrito) {
                await sesion.client.from('publicacion_suscripciones').delete().eq('usuario_id', sesion.user.id).eq('publicacion_id', d.id);
                toast('Notificaciones desactivadas', 'success');
            } else {
                var r = await sesion.client.from('publicacion_suscripciones').upsert({ usuario_id: sesion.user.id, publicacion_id: d.id });
                if (r.error) throw r.error;
                toast('Te avisaremos de nuevas respuestas', 'success');
            }
        } catch (e) { console.error(e); toast('No se pudo cambiar la notificación', 'error'); }
    }

    async function alternarGuardado(d, sesion, guardado) {
        try {
            if (guardado) {
                await sesion.client.from('publicacion_guardados').delete().eq('usuario_id', sesion.user.id).eq('publicacion_id', d.id);
                toast('Quitada de guardados', 'success');
            } else {
                var r = await sesion.client.from('publicacion_guardados').upsert({ usuario_id: sesion.user.id, publicacion_id: d.id });
                if (r.error) throw r.error;
                toast('Guardada', 'success');
            }
        } catch (e) { console.error(e); toast('No se pudo guardar', 'error'); }
    }

    function enlaceDePublicacion(d) {
        var h = d.handle ? '?u=' + encodeURIComponent(d.handle) : '';
        return location.origin + RUTA_PUBLICO + h + '#pub-' + d.id;
    }

    async function copiarEnlace(d) {
        var url = enlaceDePublicacion(d);
        try {
            await navigator.clipboard.writeText(url);
            toast('🔗 Enlace copiado', 'success');
        } catch (e) {
            window.prompt('Copia el enlace:', url);
        }
    }

    async function compartir(d) {
        var url = enlaceDePublicacion(d);
        if (navigator.share) {
            try { await navigator.share({ title: 'Publicación en Csariel\'s', url: url }); return; }
            catch (e) { if (e && e.name === 'AbortError') return; }
        }
        copiarEnlace(d);
    }

    function descargar(d) {
        if (typeof window.descargarArchivoForzado === 'function') {
            window.descargarArchivoForzado(d.mediaUrl);
        } else {
            toast('Descarga no disponible', 'error');
        }
    }

    async function etiquetar(d, sesion) {
        var handle = window.prompt('Escribe el @usuario a etiquetar (sin @):', '');
        handle = (handle || '').trim().replace(/^@/, '');
        if (!/^[A-Za-z0-9_]{1,40}$/.test(handle)) { if (handle) toast('Usuario no válido', 'warning'); return; }
        try {
            var u = await sesion.client.from('usuarios').select('id').eq('handle', handle).maybeSingle();
            if (!u.data) { toast('No encontramos a @' + handle, 'warning'); return; }
            if (u.data.id === sesion.user.id) { toast('No puedes etiquetarte a ti mismo', 'warning'); return; }
            var r = await sesion.client.from('publicacion_etiquetas').insert({
                publicacion_id: d.id, usuario_id: u.data.id, etiquetado_por: sesion.user.id
            });
            if (r.error) {
                if (r.error.code === '23505') { toast('Ya está etiquetado', 'warning'); return; }
                throw r.error;
            }
            toast('🏷️ Etiquetado @' + handle, 'success');
        } catch (e) { console.error(e); toast('No se pudo etiquetar', 'error'); }
    }

