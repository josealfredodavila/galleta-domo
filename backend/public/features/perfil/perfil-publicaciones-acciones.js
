    async function cliente() {
        var c = window.supabaseClient;
        if (c) return c;
        if (window.supabaseReady) {
            try { return await window.supabaseReady; } catch (e) { return null; }
        }
        return null;
    }

    async function sesionActual() {
        var c = await cliente();
        if (!c) return null;
        var r = await c.auth.getSession();
        return r && r.data && r.data.session ? { client: c, user: r.data.session.user } : null;
    }

    // Ruta del perfil del autor (igual que pubUrlPerfilAutor de perfil-publicaciones.js)
    function urlAutor(handle, ownerId, miId) {
        if (miId && ownerId && String(ownerId) === String(miId)) return RUTA_PROPIO;
        var h = String(handle || '').trim();
        if (!/^[A-Za-z0-9_]{1,40}$/.test(h)) return null;
        return RUTA_PUBLICO + '?u=' + encodeURIComponent(h);
    }

    function datosDeTarjeta(card) {
        var contenedor = card.querySelector('.comentarios-container');
        var handleEl = card.querySelector('.pub-autor-handle');
        var handle = handleEl ? handleEl.textContent.replace('@', '').trim() : '';
        var img = card.querySelector('.pub-media-wrap img');
        var video = card.querySelector('.pub-media-wrap video');
        return {
            id: card.dataset.id,
            ownerId: contenedor ? contenedor.dataset.dueno : '',
            handle: handle,
            mediaUrl: img ? img.src : (video ? video.src : null),
            mediaTipo: img ? 'imagen' : (video ? 'video' : null)
        };
    }

