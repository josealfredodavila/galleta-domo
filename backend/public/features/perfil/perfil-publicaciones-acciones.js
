    function visorEl() {
        var el = document.getElementById('pfVisor');
        if (el) return el;

        el = document.createElement('div');
        el.id = 'pfVisor';
        el.setAttribute('role', 'dialog');
        el.setAttribute('aria-modal', 'true');
        el.innerHTML =
            '<div class="pf-v-contador"></div>' +
            '<button type="button" class="pf-v-nav pf-v-prev" aria-label="Anterior">‹</button>' +
            '<div class="pf-v-media"></div>' +
            '<button type="button" class="pf-v-nav pf-v-next" aria-label="Siguiente">›</button>';
        document.body.appendChild(el);

        // Tocar la foto o el fondo cierra. Las flechas no cierran.
        el.addEventListener('click', function (e) {
            if (e.target.closest('.pf-v-nav')) return;
            cerrarVisor();
        });
        el.querySelector('.pf-v-prev').addEventListener('click', function (e) { e.stopPropagation(); navegar(-1); });
        el.querySelector('.pf-v-next').addEventListener('click', function (e) { e.stopPropagation(); navegar(1); });

        el.addEventListener('touchstart', function (e) {
            visor.x = e.changedTouches[0].clientX;
            visor.y = e.changedTouches[0].clientY;
        }, { passive: true });
        el.addEventListener('touchend', function (e) {
            var dx = e.changedTouches[0].clientX - visor.x;
            var dy = e.changedTouches[0].clientY - visor.y;
            if (Math.abs(dx) > 50 && Math.abs(dx) > Math.abs(dy)) navegar(dx < 0 ? 1 : -1);
            else if (dy > 110 && Math.abs(dy) > Math.abs(dx)) cerrarVisor();
        }, { passive: true });

        return el;
    }

    function pintarItem() {
        var el = visorEl();
        var caja = el.querySelector('.pf-v-media');
        var item = visor.items[visor.index];
        if (!item) return;

        caja.innerHTML = '';
        if (item.tipo === 'video') {
            var v = document.createElement('video');
            v.controls = true;
            v.playsInline = true;
            v.preload = 'auto';
            v.src = item.url;
            caja.appendChild(v);
            var p = v.play();
            if (p && typeof p.catch === 'function') p.catch(function () {});
        } else {
            var im = document.createElement('img');
            im.alt = '';
            im.src = item.url;
            caja.appendChild(im);
        }

        var varios = visor.items.length > 1;
        el.querySelector('.pf-v-contador').textContent = varios ? (visor.index + 1) + ' / ' + visor.items.length : '';
        el.querySelector('.pf-v-prev').style.display = varios && visor.index > 0 ? 'block' : 'none';
        el.querySelector('.pf-v-next').style.display = varios && visor.index < visor.items.length - 1 ? 'block' : 'none';
    }

    function navegar(dir) {
        var n = visor.index + dir;
        if (n < 0 || n >= visor.items.length) return;
        visor.index = n;
        pintarItem();
    }

    function abrirVisor(indice) {
        // Lista de medios de la página (la llena perfil-publicaciones.js)
        var lista = Array.isArray(window.listaMultimediaPerfil) ? window.listaMultimediaPerfil : [];
        if (!lista[indice]) return;

        estilosBase();
        visor.items = lista.slice();
        visor.index = indice;
        pintarItem();
        visorEl().classList.add('show');
        document.body.classList.add('pf-visor-abierto');
        document.body.style.overflow = 'hidden';
    }

    function cerrarVisor() {
        var el = document.getElementById('pfVisor');
        if (!el) return;
        var v = el.querySelector('video');
        if (v) { v.pause(); v.removeAttribute('src'); v.load(); }
        el.querySelector('.pf-v-media').innerHTML = '';
        el.classList.remove('show');
        document.body.classList.remove('pf-visor-abierto');
        document.body.style.overflow = '';
    }

    document.addEventListener('keydown', function (e) {
        var el = document.getElementById('pfVisor');
        if (!el || !el.classList.contains('show')) return;
        if (e.key === 'Escape') cerrarVisor();
        if (e.key === 'ArrowLeft') navegar(-1);
        if (e.key === 'ArrowRight') navegar(1);
    });

