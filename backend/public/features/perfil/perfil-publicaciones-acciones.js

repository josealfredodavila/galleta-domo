    function inyectarBotones() {
        document.querySelectorAll('#misPublicacionesList .publicacion-card').forEach(function (card) {
            if (card.dataset.pfMenu === '1') return;
            var stats = card.querySelector('.stats');
            if (!stats) return;

            var b = document.createElement('button');
            b.type = 'button';
            b.className = 'pf-menu-btn';
            b.setAttribute('aria-label', 'Opciones de la publicación');
            b.textContent = '☰';
            b.addEventListener('click', function (e) {
                e.stopPropagation();
                if (menuActivo) { cerrarMenu(); return; }
                abrirMenu(b, card);
            });

            stats.appendChild(b);
            card.dataset.pfMenu = '1';
        });
    }

    function observar() {
        var lista = document.getElementById('misPublicacionesList');
        if (!lista) return;
        new MutationObserver(inyectarBotones).observe(lista, { childList: true, subtree: true });
        inyectarBotones();
    }

    // Enlaces con #pub-<id> (desde "Copiar enlace"): resalta la publicación
    function resaltarDesdeHash() {
        var m = location.hash.match(/^#pub-(.+)$/);
        if (!m) return;
        var card = document.querySelector('.publicacion-card[data-id="' + m[1] + '"]');
        if (card) card.scrollIntoView({ behavior: 'smooth', block: 'center' });
    }

    estilosBase();

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', observar);
    } else {
        observar();
    }
    window.addEventListener('load', resaltarDesdeHash);

    window.pfPublicacionesAcciones = { abrirVisor: abrirVisor, cerrarVisor: cerrarVisor };
