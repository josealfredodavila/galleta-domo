    async function estadoPublicacion(publicacionId, miId, c) {
        var guardado = false, senal = null, suscrito = false;
        try {
            var g = await c.from('publicacion_guardados').select('publicacion_id').eq('usuario_id', miId).eq('publicacion_id', publicacionId).maybeSingle();
            guardado = !!g.data;
            var s = await c.from('publicacion_senales').select('tipo').eq('usuario_id', miId).eq('publicacion_id', publicacionId).maybeSingle();
            senal = s.data ? s.data.tipo : null;
            var n = await c.from('publicacion_suscripciones').select('publicacion_id').eq('usuario_id', miId).eq('publicacion_id', publicacionId).maybeSingle();
            suscrito = !!n.data;
        } catch (e) { console.warn('[Perfil] estado publicación:', e); }
        return { guardado: guardado, senal: senal, suscrito: suscrito };
    }

    function itemMenu(icono, texto, onClick, extra) {
        var b = document.createElement('button');
        b.type = 'button';
        b.innerHTML = '<span class="pf-ico">' + icono + '</span><span>' + esc(texto) + '</span>' +
            (extra ? '<span class="pf-estado">' + esc(extra) + '</span>' : '');
        b.addEventListener('click', function (e) {
            e.stopPropagation();
            cerrarMenu();
            onClick();
        });
        return b;
    }

    async function abrirMenu(boton, card) {
        cerrarMenu();
        var sesion = await sesionActual();
        if (!sesion) { toast('Inicia sesión', 'warning'); return; }

        var d = datosDeTarjeta(card);
        var soyDueno = d.ownerId && String(d.ownerId) === String(sesion.user.id);
        var est = await estadoPublicacion(d.id, sesion.user.id, sesion.client);

        var menu = document.createElement('div');
        menu.className = 'pf-menu';
        menu.setAttribute('role', 'menu');

        menu.appendChild(itemMenu('👍', 'Me interesa', function () { senalPublicacion(d, sesion, 'interesa'); }, est.senal === 'interesa' ? 'activo' : ''));
        menu.appendChild(itemMenu('🚫', 'No me interesa', function () { senalPublicacion(d, sesion, 'no_interesa'); }, est.senal === 'no_interesa' ? 'activo' : ''));
        menu.appendChild(sep());
        menu.appendChild(itemMenu('🔔', est.suscrito ? 'Dejar de notificarme' : 'Notificarme de esta publicación', function () { alternarSuscripcion(d, sesion, est.suscrito); }));
        menu.appendChild(itemMenu('🔖', est.guardado ? 'Quitar de guardados' : 'Guardar', function () { alternarGuardado(d, sesion, est.guardado); }));
        if (d.mediaUrl && d.mediaTipo === 'imagen') {
            menu.appendChild(itemMenu('⬇️', 'Descargar foto', function () { descargar(d); }));
        }
        menu.appendChild(itemMenu('🔗', 'Copiar enlace', function () { copiarEnlace(d); }));
        menu.appendChild(itemMenu('↗', 'Compartir', function () { compartir(d); }));
        if (soyDueno) {
            menu.appendChild(itemMenu('🏷️', 'Etiquetar persona', function () { etiquetar(d, sesion); }));
        }
        menu.appendChild(sep());
        if (!soyDueno) {
            var rep = itemMenu('⚑', 'Reportar publicación', function () { abrirReporte(d, sesion); });
            rep.classList.add('pf-peligro');
            menu.appendChild(rep);
        }

        document.body.appendChild(menu);
        menuActivo = menu;

        var r = boton.getBoundingClientRect();
        var top = r.bottom + 6;
        var left = Math.min(r.right - 230, window.innerWidth - 240);
        if (top + menu.offsetHeight > window.innerHeight) top = Math.max(8, r.top - menu.offsetHeight - 6);
        menu.style.top = top + 'px';
        menu.style.left = Math.max(8, left) + 'px';
    }

    function sep() {
        var s = document.createElement('div');
        s.className = 'pf-sep';
        return s;
    }

    document.addEventListener('click', function (e) {
        if (menuActivo && !menuActivo.contains(e.target) && !e.target.closest('.pf-menu-btn')) cerrarMenu();
    });

