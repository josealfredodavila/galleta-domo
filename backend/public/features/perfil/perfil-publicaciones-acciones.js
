    // Reportar
    // ------------------------------------------------------------
    var MOTIVOS = [
        ['spam', 'Spam o engañoso'],
        ['odio', 'Discurso de odio'],
        ['violencia', 'Violencia o peligro'],
        ['sexual', 'Contenido sexual'],
        ['falso', 'Información falsa'],
        ['otro', 'Otro motivo']
    ];

    function abrirReporte(d, sesion) {
        var bg = document.createElement('div');
        bg.className = 'pf-sheet-bg';
        var motivoSel = null;

        var sheet = document.createElement('div');
        sheet.className = 'pf-sheet';
        sheet.innerHTML = '<h4>REPORTAR PUBLICACIÓN</h4>';

        MOTIVOS.forEach(function (m) {
            var b = document.createElement('button');
            b.type = 'button';
            b.className = 'pf-op';
            b.textContent = m[1];
            b.addEventListener('click', function () {
                motivoSel = m[0];
                sheet.querySelectorAll('.pf-op').forEach(function (x) { x.classList.remove('sel'); });
                b.classList.add('sel');
            });
            sheet.appendChild(b);
        });

        var detalle = document.createElement('textarea');
        detalle.maxLength = 500;
        detalle.placeholder = 'Detalles (opcional)';
        sheet.appendChild(detalle);

        var acc = document.createElement('div');
        acc.className = 'pf-acciones';
        var cancel = document.createElement('button');
        cancel.type = 'button';
        cancel.textContent = 'Cancelar';
        var enviar = document.createElement('button');
        enviar.type = 'button';
        enviar.className = 'pf-primario';
        enviar.textContent = 'Enviar reporte';
        acc.appendChild(cancel);
        acc.appendChild(enviar);
        sheet.appendChild(acc);

        bg.appendChild(sheet);
        document.body.appendChild(bg);

        function cerrar() { bg.remove(); }
        cancel.addEventListener('click', cerrar);
        bg.addEventListener('click', function (e) { if (e.target === bg) cerrar(); });

        enviar.addEventListener('click', async function () {
            if (!motivoSel) { toast('Elige un motivo', 'warning'); return; }
            enviar.disabled = true;
            try {
                var r = await sesion.client.from('publicacion_reportes').insert({
                    usuario_id: sesion.user.id,
                    publicacion_id: d.id,
                    motivo: motivoSel,
                    detalle: detalle.value.trim() || null
                });
                if (r.error) {
                    if (r.error.code === '23505') toast('Ya reportaste esta publicación', 'warning');
                    else throw r.error;
                } else {
                    toast('Gracias. Revisaremos el reporte.', 'success');
                }
                cerrar();
            } catch (e) {
                console.error(e);
                toast('No se pudo enviar el reporte', 'error');
                enviar.disabled = false;
            }
        });
    }

