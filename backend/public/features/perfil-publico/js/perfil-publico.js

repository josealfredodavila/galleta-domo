    function arrancar() {
        init().catch(function (err) {
            console.error('[PerfilPublico]', err);
            mostrar(el.error);
            if (el.errorTexto) {
                el.errorTexto.textContent = 'No pudimos cargar este perfil. ' + (err.message || 'Intenta de nuevo.');
            }
        });
    }

