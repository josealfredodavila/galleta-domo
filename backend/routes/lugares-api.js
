const rateLimitStore = new Map();

function rateLimitFor(req) {
    const authenticated = Boolean(req.user && req.user.id);
    return {
        limit: authenticated ?
            CONFIG.RATE_LIMIT_AUTHENTICATED_MAX :
            CONFIG.RATE_LIMIT_ANONYMOUS_MAX,
        windowMs: CONFIG.RATE_LIMIT_WINDOW_MS
    };
}

function cleanupRateLimitStore(now) {
    let removed = 0;

    for (const [key, entry] of rateLimitStore) {
        if (!entry.hits.length ||
            now - entry.lastSeen > CONFIG.RATE_LIMIT_WINDOW_MS) {
            rateLimitStore.delete(key);
            removed++;
        }
        if (removed >= 1000) break;
    }
}

function rateLimiter(req, res, next) {
    const now = Date.now();
    const clientId = req.user && req.user.id ?
        'user:' + String(req.user.id) :
        'ip:' + getClientIp(req);

    const { limit, windowMs } = rateLimitFor(req);
    let entry = rateLimitStore.get(clientId);

    if (!entry) entry = { hits: [], lastSeen: now };

    let firstValidIndex = 0;
    while (
        firstValidIndex < entry.hits.length &&
        now - entry.hits[firstValidIndex] >= windowMs
    ) {
        firstValidIndex++;
    }

    if (firstValidIndex > 0) {
        entry.hits = entry.hits.slice(firstValidIndex);
    }

    entry.lastSeen = now;

    if (entry.hits.length >= limit) {
        metrics.rateLimited++;

        const oldest = entry.hits[0];
        const retryAfter = Math.max(
            1,
            Math.ceil((windowMs - (now - oldest)) / 1000)
        );

        res.setHeader('RateLimit-Limit', limit);
        res.setHeader('RateLimit-Remaining', 0);
        res.setHeader('Retry-After', retryAfter);

        return safeJson(res, 429, {
            error: 'TOO_MANY_REQUESTS',
            message: 'Has alcanzado el límite temporal de búsquedas.',
            retryAfterSeconds: retryAfter
        });
    }

    entry.hits.push(now);
    rateLimitStore.set(clientId, entry);

    res.setHeader('RateLimit-Limit', limit);
    res.setHeader(
        'RateLimit-Remaining',
        Math.max(0, limit - entry.hits.length)
    );

    if (rateLimitStore.size > CONFIG.RATE_LIMIT_MAX_CLIENTS) {
        cleanupRateLimitStore(now);
    }

    return next();
}

