class Semaphore {
    constructor(max, maxQueue) {
        this.max = max;
        this.maxQueue = maxQueue;
        this.active = 0;
        this.queue = [];
    }

    async acquire(waitMs) {
        if (this.active < this.max) {
            this.active++;
            return true;
        }

        if (this.queue.length >= this.maxQueue) {
            const error = new Error('CONCURRENCY_LIMIT');
            error.code = 'CONCURRENCY_LIMIT';
            throw error;
        }

        if (waitMs <= 0) {
            const error = new Error('CONCURRENCY_LIMIT');
            error.code = 'CONCURRENCY_LIMIT';
            throw error;
        }

        return new Promise((resolve, reject) => {
            const entry = { resolve: null, reject: null, timer: null };

            entry.timer = setTimeout(() => {
                const index = this.queue.indexOf(entry);
                if (index !== -1) this.queue.splice(index, 1);

                const error = new Error('CONCURRENCY_TIMEOUT');
                error.code = 'CONCURRENCY_TIMEOUT';
                reject(error);
            }, waitMs);

            entry.resolve = () => {
                clearTimeout(entry.timer);
                this.active++;
                resolve(true);
            };

            entry.reject = reject;
            this.queue.push(entry);
        });
    }

    release() {
        if (this.active > 0) this.active--;

        const next = this.queue.shift();
        if (next) next.resolve();
    }
}

