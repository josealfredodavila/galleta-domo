function calculateTourismScore(place, normalizedQuery, origin) {
    const weights = CONFIG.SCORING;
    let score = 0;

    const name = normalizeText(place.displayName?.text || '');
    const address = normalizeText(place.formattedAddress || '');
    const rating = place.rating || 0;
    const reviews = place.userRatingCount || 0;
    const types = place.types || [];

    if (name && normalizedQuery) {
        if (name === normalizedQuery) {
            score += weights.EXACT_NAME_MATCH * 1.5;
        } else if (name.includes(normalizedQuery)) {
            score += weights.EXACT_NAME_MATCH;
        } else {
            const words = normalizedQuery.split(' ').filter(w => w.length > 2);
            score += words.filter(w => name.includes(w)).length *
                weights.WORD_MATCH;
        }
    }

    if (address && normalizedQuery && address.includes(normalizedQuery)) {
        score += weights.ADDRESS_MATCH;
    }

    if (rating > 0) score += rating * weights.RATING_WEIGHT;
    score += Math.min(reviews * weights.REVIEW_WEIGHT, weights.MAX_REVIEW_BOOST);

    for (const type of types) {
        if (HIGH_VALUE_TYPES.has(type)) {
            score += weights.HIGH_VALUE_TYPE;
            break;
        }
    }

    if (place.businessStatus === 'OPERATIONAL') {
        score += weights.OPERATIONAL_BONUS;
    } else if (
        place.businessStatus === 'CLOSED_PERMANENTLY' ||
        place.businessStatus === 'CLOSED_TEMPORARILY'
    ) {
        score -= weights.CLOSED_PENALTY;
    }

    if (origin && place.location) {
        const distance = haversineMeters(
            origin.lat,
            origin.lng,
            place.location.latitude,
            place.location.longitude
        );

        place._distanceMeters = distance;

        if (distance <= 1000) score += weights.DISTANCE_1KM;
        else if (distance <= 3000) score += weights.DISTANCE_3KM;
        else if (distance <= 5000) score += weights.DISTANCE_5KM;
        else if (distance <= 10000) score += weights.DISTANCE_10KM;
        else if (distance <= 25000) score += weights.DISTANCE_25KM;
    }

    return Math.round(score);
}

