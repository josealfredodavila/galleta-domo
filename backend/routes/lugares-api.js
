function applyFilters(places, query) {
    let filtered = places;

    if (query.minRating > 0) {
        filtered = filtered.filter(place =>
            (place.rating || 0) >= query.minRating
        );
    }

    if (query.priceLevels.length) {
        filtered = filtered.filter(place =>
            !place.priceLevel ||
            query.priceLevels.includes(place.priceLevel)
        );
    }

    if (query.openNow) {
        filtered = filtered.filter(place => place.openNow === true);
    }

    return filtered;
}

function sortPlaces(places, sort) {
    const sorted = [...places];

    if (sort === 'distancia') {
        sorted.sort((a, b) =>
            (a.distanceMeters ?? Number.MAX_SAFE_INTEGER) -
            (b.distanceMeters ?? Number.MAX_SAFE_INTEGER)
        );
        return sorted;
    }

    if (sort === 'rating') {
        sorted.sort((a, b) => {
            if ((b.rating || 0) !== (a.rating || 0)) {
                return (b.rating || 0) - (a.rating || 0);
            }
            return b.reviewCount - a.reviewCount;
        });
        return sorted;
    }

    if (sort === 'populares') {
        sorted.sort((a, b) => b.reviewCount - a.reviewCount);
        return sorted;
    }

    sorted.sort((a, b) => {
        if (b.score !== a.score) return b.score - a.score;
        return String(a.placeId).localeCompare(String(b.placeId));
    });

    return sorted;
}

function deduplicatePlaces(places) {
    const seen = new Set();
    const unique = [];

    for (const place of places) {
        const key = place.id ||
            (normalizeText(place.displayName?.text) + '|' +
            normalizeText(place.formattedAddress));

        if (seen.has(key)) continue;
        seen.add(key);
        unique.push(place);
    }

    return unique;
}

