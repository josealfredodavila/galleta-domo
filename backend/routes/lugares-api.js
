function dentroDelLimite(uid) {
    const ahora = Date.now();

    if (conteoPorUsuario.size > CONFIG.GEO_RATE_LIMIT_MAX_USERS) {
        conteoPorUsuario.clear();
    }

    const registro = conteoPorUsuario.get(uid);

    if (!registro || ahora - registro.inicio > 60000) {
        conteoPorUsuario.set(uid, { inicio: ahora, n: 1 });
        return true;
    }

    if (registro.n >= CONFIG.GEO_RATE_LIMIT_PER_MINUTE) {
        return false;
    }

    registro.n++;
    return true;
}

