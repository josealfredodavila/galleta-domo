function transformPlace(place, normalizedQuery, origin) {
    const location = place.location || null;
    const types = place.types || [];
    const placeId = place.id || null;

    const photos = (place.photos || []).slice(0, 5).map(photo => ({
        name: photo.name || null,
        width: photo.widthPx || null,
        height: photo.heightPx || null,
        authorAttributions: photo.authorAttributions || []
    }));

    const wasSeenBefore = placeId ? placeIdCache.has(placeId) : false;
    if (wasSeenBefore) metrics.placeIdCacheHits++;

    const transformed = {
        placeId,
        name: place.displayName?.text || 'Lugar sin nombre',
        address: place.formattedAddress || '',
        location: location ? {
            lat: location.latitude,
            lng: location.longitude
        } : null,
        category: getPrimaryCategory(types),
        types,
        typeLabels: types.map(translateType),
        rating: place.rating || null,
        reviewCount: place.userRatingCount || 0,
        priceLevel: place.priceLevel || null,
        openNow: place.currentOpeningHours?.openNow ?? null,
        businessStatus: place.businessStatus || 'UNKNOWN',
        photos,
        distanceMeters: origin && location ?
            haversineMeters(
                origin.lat, origin.lng,
                location.latitude, location.longitude
            ) : null,
        mapUrl: placeId ?
            'https://www.google.com/maps/search/?api=1&query_place_id=' +
            encodeURIComponent(placeId) : null,
        score: 0,
        seenBefore: wasSeenBefore
    };

    transformed.score = calculateTourismScore(
        place, normalizedQuery, origin
    );

    return transformed;
}

