function recordLatency(milliseconds) {
    metrics.latencyMs.last = milliseconds;
    latencyBuffer[latencyIndex] = milliseconds;
    latencyIndex = (latencyIndex + 1) % LATENCY_BUFFER_SIZE;

    if (latencyCount < LATENCY_BUFFER_SIZE) latencyCount++;
    if (metrics.searches % 10 !== 0) return;

    const values = Array.from(latencyBuffer.slice(0, latencyCount))
        .sort((a, b) => a - b);

    if (!values.length) return;

    function percentile(p) {
        const index = Math.min(
            values.length - 1,
            Math.ceil((p / 100) * values.length) - 1
        );
        return values[Math.max(0, index)];
    }

    metrics.latencyMs.p50 = percentile(50);
    metrics.latencyMs.p95 = percentile(95);
    metrics.latencyMs.p99 = percentile(99);
}

