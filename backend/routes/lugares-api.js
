async function obtenerDireccion(lat, lng) {
    const clave = lat + ',' + lng;

    const cached = cacheDirecciones.get(clave);
    if (cached) return cached;

    const apiKey = process.env.GOOGLE_MAPS_API_KEY;
    if (!apiKey) throw new Error('MISSING_GOOGLE_MAPS_API_KEY');

    const url = new URL(CONFIG.GEOCODE_ENDPOINT);
    url.searchParams.set('latlng', clave);
    url.searchParams.set('language', 'es');
    url.searchParams.set('key', apiKey);

    const controller = new AbortController();
    const timeout = setTimeout(
        () => controller.abort(),
        CONFIG.REQUEST_TIMEOUT_MS
    );

    let data;

    try {
        const response = await fetch(url, { signal: controller.signal });
        if (!response.ok) throw new Error('GEOCODE_HTTP_' + response.status);
        data = await response.json();
    } finally {
        clearTimeout(timeout);
    }

    if (data.status === 'ZERO_RESULTS') {
        return {
            ciudad: null,
            municipio: null,
            estado_region: null,
            pais: null
        };
    }

    if (data.status !== 'OK' || !Array.isArray(data.results)) {
        throw new Error('geocode_' + (data.status || 'desconocido'));
    }

    const components = data.results.flatMap(result =>
        result.address_components || []
    );

    const buscar = function(type) {
        const component = components.find(item =>
            Array.isArray(item.types) && item.types.includes(type)
        );
        return component ? component.long_name : null;
    };

    const value = {
        ciudad: buscar('locality') ||
            buscar('sublocality') ||
            buscar('administrative_area_level_3'),
        municipio: buscar('administrative_area_level_2'),
        estado_region: buscar('administrative_area_level_1'),
        pais: buscar('country')
    };

    cacheDirecciones.set(clave, value);
    return value;
}

