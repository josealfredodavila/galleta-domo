function buildQuery(req) {
    const rawQuery = String(req.query.q || '').trim();
    const normalizedQuery = normalizeText(rawQuery);
    const intent = detectIntent(normalizedQuery);

    const sanitizedType = sanitizeIncludedType(req.query.tipo);
    const includedTypes = sanitizedType ?
        [sanitizedType] : intent.includedTypes;

    const ignoredTipo = req.query.tipo && !sanitizedType ?
        String(req.query.tipo) : null;

    const latRaw = req.query.lat;
    const lngRaw = req.query.lng;
    const hasLatLngParams = latRaw !== undefined || lngRaw !== undefined;

    const lat = hasLatLngParams ? toFloat(latRaw, NaN) : NaN;
    const lng = hasLatLngParams ? toFloat(lngRaw, NaN) : NaN;

    let hasLocation = false;
    let invalidCoordinates = false;

    if (hasLatLngParams) {
        if (!isValidCoordinate(lat, lng)) invalidCoordinates = true;
        else hasLocation = true;
    }

    const radius = toInt(
        req.query.radio,
        CONFIG.DEFAULT_RADIUS_METERS,
        100,
        CONFIG.MAX_RADIUS_METERS
    );

    const pageSize = toInt(
        req.query.max,
        CONFIG.DEFAULT_PAGE_SIZE,
        1,
        CONFIG.MAX_PAGE_SIZE
    );

    const minRating = clampNumber(toFloat(req.query.rating, 0), 0, 5);
    const priceLevels = normalizePriceLevels(req.query.precio);
    const openNow = String(req.query.abierto || '').toLowerCase() === 'true';

    const sort = normalizeText(req.query.orden || 'relevancia');
    const allowedSorts = ['relevancia', 'distancia', 'rating', 'populares'];
    const safeSort = allowedSorts.includes(sort) ? sort : 'relevancia';

    const cursor = req.query.cursor || null;

    return {
        rawQuery,
        normalizedQuery,
        includedTypes,
        intent: intent.intent,
        ignoredTipo,
        lat: hasLocation ? lat : null,
        lng: hasLocation ? lng : null,
        hasLocation,
        invalidCoordinates,
        radius,
        pageSize,
        minRating,
        priceLevels,
        openNow,
        sort: safeSort,
        cursor
    };
}

// ================================================================
// CURSOR FIRMADO
// ================================================================

function buildQueryFingerprint(query) {
    return hashString([
        query.normalizedQuery,
        query.includedTypes.join(','),
        query.lat ?? '',
        query.lng ?? '',
        query.radius,
        query.pageSize,
        query.minRating,
        query.priceLevels.join(','),
        query.openNow,
        query.sort
    ].join('|'));
}

function buildCacheKey(query) {
    return hashString(
        buildQueryFingerprint(query) + '|' + (query.cursor || '')
    );
}

function signCursor(payload) {
    return crypto.createHmac('sha256', EFFECTIVE_CURSOR_SECRET)
        .update(payload)
        .digest('base64url');
}

function encodeCursor(nextPageToken, query) {
    if (!nextPageToken) return null;

    const payload = JSON.stringify({
        token: nextPageToken,
        expiresAt: Date.now() + CONFIG.CURSOR_TTL_MS,
        fingerprint: buildQueryFingerprint(query)
    });

    const encoded = Buffer.from(payload).toString('base64url');
    return encoded + '.' + signCursor(encoded);
}

function decodeCursor(cursor, query) {
    if (!cursor) return null;

    try {
        const parts = String(cursor).split('.');
        if (parts.length !== 2) return null;

        const encoded = parts[0];
        const suppliedSignature = parts[1];
        const expectedSignature = signCursor(encoded);

        const suppliedBuffer = Buffer.from(suppliedSignature);
        const expectedBuffer = Buffer.from(expectedSignature);

        if (suppliedBuffer.length !== expectedBuffer.length) return null;

        if (!crypto.timingSafeEqual(suppliedBuffer, expectedBuffer) ) {
            return null;
        }

        const decoded = JSON.parse(
            Buffer.from(encoded, 'base64url').toString('utf8')
        );

        if (!decoded.token || decoded.expiresAt < Date.now()) return null;
        if (decoded.fingerprint !== buildQueryFingerprint(query)) return null;

        return decoded.token;
    } catch (error) {
        return null;
    }
}

