async function executeSearch(query) {
    const cacheKey = buildCacheKey(query);

    if (CONFIG.RESPONSE_CACHE_ENABLED) {
        const cached = responseCache.get(cacheKey);

        if (cached) {
            metrics.cacheHits++;
            return {
                ...cached,
                meta: { ...cached.meta, cache: 'HIT' }
            };
        }
    }

    metrics.cacheMisses++;

    if (singleFlight.has(cacheKey)) {
        metrics.singleFlightHits++;
        return singleFlight.get(cacheKey);
    }

    const execution = (async function() {
        let pageToken = decodeCursor(query.cursor, query);

        if (query.cursor && !pageToken) {
            const error = new Error('INVALID_CURSOR');
            error.code = 'INVALID_CURSOR';
            throw error;
        }

        let allRawPlaces = [];
        let lastNextPageToken = null;
        let pagesFetched = 0;

        while (
            allRawPlaces.length < query.pageSize &&
            pagesFetched < CONFIG.MAX_PAGES_PER_SEARCH
        ) {
            const data = await callGooglePlaces(query, pageToken);
            const batch = data.places || [];

            allRawPlaces.push(...batch);
            lastNextPageToken = data.nextPageToken || null;
            pageToken = lastNextPageToken;
            pagesFetched++;

            if (!lastNextPageToken || !batch.length) break;
        }

        allRawPlaces = deduplicatePlaces(allRawPlaces);

        const origin = query.hasLocation ?
            { lat: query.lat, lng: query.lng } : null;

        let places = allRawPlaces.map(place =>
            transformPlace(place, query.normalizedQuery, origin)
        );

        places = applyFilters(places, query);
        places = sortPlaces(places, query.sort);
        places = places.slice(0, query.pageSize);

        for (const place of places) {
            if (place.placeId) {
                placeIdCache.set(place.placeId, { cachedAt: Date.now() });
            }
        }

        const nextCursor = encodeCursor(lastNextPageToken, query);

        const response = {
            results: places,
            meta: {
                total: places.length,
                query: query.rawQuery,
                detectedIntent: query.intent,
                appliedTypes: query.includedTypes,
                ignoredTipo: query.ignoredTipo || null,
                sort: query.sort,
                provider: 'Google Places API (New)',
                version: '5.4',
                timestamp: new Date().toISOString(),
                locationApplied: query.hasLocation,
                radiusMeters: query.hasLocation ? query.radius : null,
                filters: {
                    minRating: query.minRating || null,
                    priceLevels: query.priceLevels.length ?
                        query.priceLevels : null,
                    openNow: query.openNow
                },
                pagination: {
                    hasNextPage: Boolean(nextCursor),
                    nextCursor
                },
                pagesFetched,
                cache: CONFIG.RESPONSE_CACHE_ENABLED ? 'MISS' : 'DISABLED'
            }
        };

        metrics.resultsReturned += places.length;

        if (CONFIG.RESPONSE_CACHE_ENABLED) {
            responseCache.set(cacheKey, response);
        }

        return response;
    })();

    singleFlight.set(cacheKey, execution);

    try {
        return await execution;
    } finally {
        singleFlight.delete(cacheKey);
    }
}

