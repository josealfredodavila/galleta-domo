// ================================================================
// ROUTES/PAY/STRIPE-CONNECT.JS
// CSARIEL'S PAY - ONBOARDING DE STRIPE CONNECT
// ================================================================
// Endpoints:
//   GET  /api/pay/stripe-connect/estado    (privado)
//   POST /api/pay/stripe-connect/onboarding (privado)
//   GET  /api/pay/stripe-connect/retorno    (privado, recibe al user
//                                             de vuelta de Stripe)
//
// Flujo:
//   1. Vendedor pide iniciar onboarding -> POST /onboarding
//   2. Backend crea (o reusa) cuenta Connect Express
//   3. Backend genera Account Link de Stripe
//   4. Frontend redirige al vendedor a la URL de Stripe
//   5. Vendedor completa datos en Stripe
//   6. Stripe redirige a /features/pay/vincular-stripe.html
//   7. Frontend consulta /estado para ver si está listo
//
// Cómo se guarda el stripe_account_id:
//   No tocamos el esquema de Supabase. El stripe_account_id se
//   resuelve por email del usuario contra la API de Stripe.
//   Si cambia el email, se crea una nueva cuenta. Es un caso raro.
// ================================================================

'use strict';

const express = require('express');
const router = express.Router();
const Stripe = require('stripe');

const { supabaseAdmin } = require('../../config/supabase');
const logger = require('../../utils/logger');
const { verificarToken } = require('../../middleware/auth');
const errors = require('../../services/pay/errors');

// ================================================================
// CONFIGURACIÓN
// ================================================================

const STRIPE_SECRET_KEY = process.env.STRIPE_SECRET_KEY;
const PUBLIC_URL = process.env.PUBLIC_URL || '';

// ================================================================
// CLIENTE STRIPE
// ================================================================

let stripeClient = null;

function obtenerCliente() {
    if (!STRIPE_SECRET_KEY) {
        throw errors.errorProveedorNoConfigurado('stripe (falta STRIPE_SECRET_KEY)');
    }

    if (!stripeClient) {
        stripeClient = new Stripe(STRIPE_SECRET_KEY, {
            timeout: 20000,
            maxNetworkRetries: 2,
            appInfo: {
                name: 'Csariels Pay',
                version: '1.0.0'
            }
        });
    }

    return stripeClient;
}

// ================================================================
// RESOLVER CUENTA CONNECT DEL USUARIO
// ================================================================
// Busca una cuenta Connect asociada al email del usuario.
// Si no existe, la crea.
// ================================================================

async function resolverOCrearCuentaConnect(usuario) {
    const stripe = obtenerCliente();

    const email = usuario.email;
    if (!email) {
        throw errors.errorParametroRequerido('email del usuario');
    }

    // ---------- 1) Buscar por email ----------
    let cuentaExistente = null;

    try {
        const lista = await stripe.accounts.list({
            email: email,
            limit: 1
        });

        if (lista && lista.data && lista.data.length > 0) {
            cuentaExistente = lista.data[0];
        }
    } catch (errList) {
        logger.warning(`[Stripe Connect] Error buscando cuenta por email: ${errList.message}`);
        // Continuar: quizá no existe y hay que crearla
    }

    if (cuentaExistente) {
        return cuentaExistente;
    }

    // ---------- 2) Crear cuenta Connect Express ----------
    let nuevaCuenta;

    try {
        nuevaCuenta = await stripe.accounts.create({
            type: 'express',
            email: email,
            country: 'MX',
            business_type: 'individual',
            capabilities: {
                transfers: { requested: true },
                card_payments: { requested: true }
            },
            settings: {
                payouts: {
                    schedule: {
                        interval: 'manual'
                    }
                }
            },
            metadata: {
                csariels_usuario_id: usuario.id,
                csariels_created_from: 'csariels_pay_onboarding'
            }
        });
    } catch (errCreate) {
        logger.error(`[Stripe Connect] Error creando cuenta Connect: ${errCreate.message}`);

        if (errCreate.type === 'StripeInvalidRequestError') {
            throw errors.errorProveedorRechazo('stripe', errCreate.message, {
                codigo: errCreate.code || null
            });
        }

        throw errors.errorProveedorErrorTemporal('stripe', {
            motivo: errCreate.message
        });
    }

    logger.info(`[Stripe Connect] Cuenta Connect creada: ${nuevaCuenta.id} (${email})`);

    return nuevaCuenta;
}

// ================================================================
// GET /api/pay/stripe-connect/estado
// PRIVADO - ¿Está el vendedor habilitado para retirar por tarjeta?
// ================================================================

router.get(
    '/estado',
    verificarToken,
    async function (req, res) {
        try {
            const usuario = req.usuario;

            // Buscar cuenta Connect por email
            const stripe = obtenerCliente();

            let cuenta = null;
            try {
                const lista = await stripe.accounts.list({
                    email: usuario.email,
                    limit: 1
                });

                if (lista && lista.data && lista.data.length > 0) {
                    cuenta = lista.data[0];
                }
            } catch (errList) {
                logger.warning(`[Stripe Connect] Error consultando cuenta: ${errList.message}`);
            }

            if (!cuenta) {
                return res.status(200).json({
                    success: true,
                    data: {
                        vinculada: false,
                        habilitada: false,
                        mensaje: 'Aún no has vinculado tu cuenta de Stripe para retiros por tarjeta.'
                    }
                });
            }

            // Consultar estado completo (por si cambió desde el último list)
            let cuentaCompleta;
            try {
                cuentaCompleta = await stripe.accounts.retrieve(cuenta.id);
            } catch (errRetrieve) {
                logger.warning(`[Stripe Connect] Error obteniendo cuenta ${cuenta.id}: ${errRetrieve.message}`);
                cuentaCompleta = cuenta;
            }

            return res.status(200).json({
                success: true,
                data: {
                    vinculada: true,
                    habilitada: cuentaCompleta.payouts_enabled === true &&
                                cuentaCompleta.charges_enabled === true,
                    payouts_enabled: cuentaCompleta.payouts_enabled === true,
                    charges_enabled: cuentaCompleta.charges_enabled === true,
                    details_submitted: cuentaCompleta.details_submitted === true,
                    pais: cuentaCompleta.country,
                    moneda_default: cuentaCompleta.default_currency,
                    requirements_pendientes: cuentaCompleta.requirements && cuentaCompleta.requirements.currently_due
                        ? cuentaCompleta.requirements.currently_due
                        : [],
                    mensaje: cuentaCompleta.payouts_enabled
                        ? 'Tu cuenta de Stripe está lista para recibir retiros por tarjeta.'
                        : 'Tu cuenta de Stripe aún necesita información. Continúa el proceso.'
                }
            });

        } catch (err) {
            logger.error(`[Stripe Connect] Error en estado: ${err.message}`);
            return errors.responderError(res, err);
        }
    }
);

// ================================================================
// POST /api/pay/stripe-connect/onboarding
// PRIVADO - Genera una URL de onboarding de Stripe.
// ================================================================

router.post(
    '/onboarding',
    verificarToken,
    async function (req, res) {
        try {
            const usuario = req.usuario;

            // ---------- 1) Obtener (o crear) cuenta Connect ----------
            const cuenta = await resolverOCrearCuentaConnect(usuario);

            // ---------- 2) Generar Account Link ----------
            const stripe = obtenerCliente();

            const returnUrlBase = PUBLIC_URL || '';
            const refreshUrl = returnUrlBase
                ? `${returnUrlBase}/features/pay/vincular-stripe.html?estado=refrescar`
                : `/features/pay/vincular-stripe.html?estado=refrescar`;
            const returnUrl = returnUrlBase
                ? `${returnUrlBase}/features/pay/vincular-stripe.html?estado=listo`
                : `/features/pay/vincular-stripe.html?estado=listo`;

            let accountLink;
            try {
                accountLink = await stripe.accountLinks.create({
                    account: cuenta.id,
                    refresh_url: refreshUrl,
                    return_url: returnUrl,
                    type: 'account_onboarding',
                    collect: 'currently_due'
                });
            } catch (errLink) {
                logger.error(`[Stripe Connect] Error creando Account Link: ${errLink.message}`);
                throw errors.errorProveedorErrorTemporal('stripe', {
                    motivo: errLink.message
                });
            }

            logger.info(`[Stripe Connect] Account Link generado para ${usuario.email}`);

            return res.status(200).json({
                success: true,
                data: {
                    url: accountLink.url,
                    expires_at: accountLink.expires_at,
                    account_id: cuenta.id
                }
            });

        } catch (err) {
            logger.error(`[Stripe Connect] Error en onboarding: ${err.message}`);
            return errors.responderError(res, err);
        }
    }
);

// ================================================================
// EXPORTAR
